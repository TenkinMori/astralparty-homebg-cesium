param(
    [string]$AndroidJar = "",
    [string]$D8Jar = "",
    [switch]$SkipJava,
    [switch]$PackageZip
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

function Find-AndroidJar {
    param([string]$Explicit)
    if ($Explicit -and (Test-Path $Explicit)) { return $Explicit }
    $sdkCandidates = @(
        $env:ANDROID_HOME,
        $env:ANDROID_SDK_ROOT,
        "D:\Android\Sdk",
        "C:\Android\Sdk",
        "$env:LOCALAPPDATA\Android\Sdk"
    ) | Where-Object { $_ -and (Test-Path $_) }
    foreach ($sdk in $sdkCandidates) {
        $jars = Get-ChildItem "$sdk\platforms\*\android.jar" -ErrorAction SilentlyContinue | Sort-Object FullName -Descending
        if ($jars) { return $jars[0].FullName }
    }
    return $null
}

function Find-D8Jar {
    param([string]$Explicit)
    if ($Explicit -and (Test-Path $Explicit)) { return $Explicit }
    $sdkCandidates = @(
        $env:ANDROID_HOME,
        $env:ANDROID_SDK_ROOT,
        "D:\Android\Sdk",
        "C:\Android\Sdk",
        "$env:LOCALAPPDATA\Android\Sdk"
    ) | Where-Object { $_ -and (Test-Path $_) }
    foreach ($sdk in $sdkCandidates) {
        $jars = Get-ChildItem "$sdk\build-tools\*\lib\d8.jar" -ErrorAction SilentlyContinue | Sort-Object FullName -Descending
        if ($jars) { return $jars[0].FullName }
    }
    return $null
}

if (-not $SkipJava) {
    $resolvedAndroidJar = Find-AndroidJar -Explicit $AndroidJar
    $resolvedD8Jar = Find-D8Jar -Explicit $D8Jar
    if (-not $resolvedAndroidJar -or -not $resolvedD8Jar) {
        throw "未找到 Android SDK 的 android.jar 或 d8.jar。请设置 ANDROID_HOME、传入 -AndroidJar / -D8Jar，或使用 -SkipJava 复用仓库内嵌 DEX。"
    }

    $javaSrc = Join-Path $root 'android\java\homebg\VideoDecoder.java'
    $tmpJavaOut = Join-Path $root 'build\android-dex'
    $classesDir = Join-Path $tmpJavaOut 'classes'
    $dexDir = Join-Path $tmpJavaOut 'dex'
    if (Test-Path $tmpJavaOut) { Remove-Item -Recurse -Force $tmpJavaOut }
    New-Item -ItemType Directory -Force $classesDir, $dexDir | Out-Null

    Write-Host "Compiling VideoDecoder.java with $resolvedAndroidJar ..."
    & javac --release 8 -cp $resolvedAndroidJar -d $classesDir $javaSrc
    if ($LASTEXITCODE -ne 0) { throw "javac 编译失败" }

    $classFiles = Get-ChildItem $classesDir -Recurse -Filter '*.class' | Select-Object -ExpandProperty FullName
    Write-Host "Running d8 -> classes.dex ..."
    & java -cp $resolvedD8Jar com.android.tools.r8.D8 --min-api 26 --output $dexDir $classFiles
    if ($LASTEXITCODE -ne 0) { throw "d8 打包失败" }

    $dexPath = Join-Path $dexDir 'classes.dex'
    $dexBytes = [System.IO.File]::ReadAllBytes($dexPath)
    $dexBase64 = [System.Convert]::ToBase64String($dexBytes)

    # 同步保存 classes.dex / VideoDecoder.class 备份并生成 C# 内嵌 DEX 源码
    New-Item -ItemType Directory -Force (Join-Path $root 'android\java\dex'), (Join-Path $root 'android\java\classes\homebg') | Out-Null
    Copy-Item $dexPath (Join-Path $root 'android\classes.dex') -Force
    Copy-Item $dexPath (Join-Path $root 'android\java\dex\classes.dex') -Force
    Copy-Item (Join-Path $classesDir 'homebg\VideoDecoder.class') (Join-Path $root 'android\java\classes\homebg\VideoDecoder.class') -Force
    $genCs = @"
// <auto-generated by build.ps1>
namespace HomeBackgroundMod
{
    internal static class AndroidVideoDex
    {
        internal const string Base64 = "$dexBase64";
    }
}
"@
    [System.IO.File]::WriteAllText((Join-Path $root 'src\HomeBackgroundMod\AndroidVideoDex.g.cs'), $genCs, [System.Text.UTF8Encoding]::new($false))
}

dotnet build "$root\src\HomeBackgroundMod\HomeBackgroundMod.csproj" -c Release -v q --nologo
if ($LASTEXITCODE -ne 0) { throw "dotnet build 失败" }

$builtDll = Join-Path $root 'src\HomeBackgroundMod\bin\Release\netstandard2.0\HomeBackgroundMod.dll'
$manifestJson = Join-Path $root 'src\HomeBackgroundMod\HomeBackgroundMod.json'
$iconPng = Join-Path $root 'src\HomeBackgroundMod\icon.png'
$bgPng = Join-Path $root 'src\HomeBackgroundMod\assets\bg.png'

$out = Join-Path $root 'dist\HomeBackgroundMod'
if (Test-Path $out) { Remove-Item -Recurse -Force $out }
New-Item -ItemType Directory -Force "$out\assets" | Out-Null
Copy-Item $builtDll $out -Force
Copy-Item $manifestJson $out -Force
Copy-Item $iconPng $out -Force
Copy-Item "$root\LICENSE" $out -Force
Copy-Item $bgPng "$out\assets\" -Force

foreach ($legacyDir in @((Join-Path $root 'dist\android'), (Join-Path $root 'dist\pc'))) {
    New-Item -ItemType Directory -Force "$legacyDir\assets" | Out-Null
    Copy-Item $builtDll $legacyDir -Force
    Copy-Item $manifestJson $legacyDir -Force
    Copy-Item $bgPng "$legacyDir\assets\" -Force
}

if ($PackageZip) {
    $zipPath = Join-Path $root 'dist\HomeBackgroundMod-1.2.3.zip'
    if (Test-Path $zipPath) { Remove-Item -Force $zipPath }
    Compress-Archive -Path $out -DestinationPath $zipPath -CompressionLevel Optimal
    Write-Host "ZIP -> $zipPath"
}

Write-Host "OK -> $out"
Get-ChildItem $out -Recurse -File | Select-Object FullName, Length | Format-Table -AutoSize
